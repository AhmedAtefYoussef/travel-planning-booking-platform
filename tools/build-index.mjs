// Regenerates README.md: every Milestone 1 endpoint of the project description (section 8, mandatory only)
// -> requirement IDs -> Jira key -> the screenshots and live-run notes that show it working in Swagger.
// Evidence is matched by requirement ID found in a file's path (e.g. "htl-01/", "01-ACC-01-...",
// "gen13") or, for live-run.md notes, in the note's text. Run from the branch root:
//   node tools/build-index.mjs
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';

const ROOT = new URL('..', import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1');
const { endpoints, jira } = JSON.parse(
  readFileSync(join(ROOT, 'tools', 'endpoints.json'), 'utf8'),
);
const sources = JSON.parse(
  readFileSync(join(ROOT, 'tools', 'sources.json'), 'utf8'),
);

const REQ = /\b(acc|flt|htl|pay|itn|blg|gen)[-_]?(\d{2}a?)(?![0-9])/gi;
const norm = (prefix, num) => `${prefix.toUpperCase()}-${num}`;

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const full = join(dir, name);
    return statSync(full).isDirectory() ? walk(full) : [full];
  });
}

const files = walk(join(ROOT, 'evidence'))
  .map((f) => relative(ROOT, f).split(sep).join('/'))
  .filter((f) => /\.(png|jpe?g|pdf|md)$/i.test(f) && !f.endsWith('/README.md'));

/** requirement ID -> evidence files */
const byReq = new Map();
for (const file of files) {
  const ids = new Set(
    [...file.matchAll(REQ)].map((m) => norm(m[1], m[2])),
  );
  if (file.endsWith('.md')) {
    for (const m of readFileSync(join(ROOT, file), 'utf8').matchAll(REQ)) {
      ids.add(norm(m[1], m[2]));
    }
  }
  for (const id of ids) byReq.set(id, [...(byReq.get(id) ?? []), file]);
}

const link = (f) => `[${f.split('/').slice(-1)[0]}](${encodeURI(f)})`;
const groups = [...new Set(endpoints.map((e) => e.group))];
const gaps = [];
let out = `# Milestone 1 Swagger evidence

The single home of every Swagger UI screenshot and live-run note recorded for Milestone 1 (backend,
evaluated through Swagger UI, brief section 13.1). **This branch is never merged** into \`develop\` or
\`main\`: pull requests link to its files instead. It consolidates the former per-member evidence
branches listed under [Sources](#sources).

- **Layout:** \`evidence/<area>/\`. Each area keeps its original README, which describes every
  screenshot, and its \`<req-id>/\` folders.
- **Index below:** generated by \`node tools/build-index.mjs\` from \`tools/endpoints.json\`, which lists the
  section 8 endpoints with their requirement IDs and Jira keys. Do not edit the index by hand; add
  evidence under \`evidence/<area>/<req-id>/\` and regenerate.

`;

for (const group of groups) {
  out += `## ${group}\n\n| Endpoint | Requirement | Jira | Evidence |\n|---|---|---|---|\n`;
  for (const e of endpoints.filter((x) => x.group === group)) {
    const ev = [...new Set(e.requirements.flatMap((r) => byReq.get(r) ?? []))];
    const shown = ev.slice(0, 6).map(link).join('<br>');
    const more = ev.length > 6 ? `<br>… ${ev.length - 6} more` : '';
    if (!ev.length) gaps.push(e);
    out += `| \`${e.method} ${e.path}\` | ${e.requirements.join(', ')} | ${e.requirements
      .map((r) => jira[r] ?? '-')
      .join(', ')} | ${ev.length ? shown + more : ':warning: none yet'} |\n`;
  }
  out += '\n';
}

out += `## Coverage\n\n${endpoints.length - gaps.length} of ${endpoints.length} endpoints have evidence.\n\n`;
if (gaps.length) {
  out += `### Coverage gaps\n\n| Endpoint | Requirement |\n|---|---|\n${gaps
    .map((e) => `| \`${e.method} ${e.path}\` | ${e.requirements.join(', ')} |`)
    .join('\n')}\n\n`;
}

out += `## Sources\n\nEach former evidence branch was imported as one commit, crediting its original author. The old
branches were deleted after the import; restore one with \`git push origin <sha>:refs/heads/<branch>\`.

| Former branch | Tip SHA | Author | Imported to |\n|---|---|---|---|\n${sources
  .map((s) => `| \`${s.branch}\` | \`${s.sha}\` | ${s.author} | \`evidence/${s.area}/\` |`)
  .join('\n')}\n`;

writeFileSync(join(ROOT, 'README.md'), out);
console.log(
  `README.md: ${endpoints.length} endpoints, ${files.length} evidence files, ${gaps.length} gap(s)`,
);
for (const g of gaps) console.log(`  gap: ${g.method} ${g.path} (${g.requirements.join(', ')})`);
